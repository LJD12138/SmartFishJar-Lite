/***********************************************************************************************************************
-----函数功能    12V总线电源开关
-----说明(备注)  none
-----传入参数    en: true=开  false=关
-----输出参数    none
-----返回值      none
************************************************************************************************************************/ 
void vGPIO_12VPowerSwitch(bool en)
{
    if(en == true)
        gpio12V_ON();
    else
        gpio12V_OFF();
}



