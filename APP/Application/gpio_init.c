/***********************************************************************************************************************
-----函数功能    IO口初始化
-----说明(备注)  none
-----传入参数    none
-----输出参数    none
-----返回值      none
************************************************************************************************************************/ 
void vGPIO_Init(void)
{
    /* 12V电源使能 PC2，默认低电平（关闭） */
    rcu_periph_clock_enable(gpio12V_EN_RCU);
    gpio_init(gpio12V_EN_PORT, GPIO_MODE_OUT_PP, GPIO_OSPEED_2MHZ, gpio12V_EN_PIN);
    gpio12V_OFF();

}




